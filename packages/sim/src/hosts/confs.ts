const CLUSTER_INDEXES = ['os', 'app', 'network'];

export function clusterIndexesConf(world?: World): string {
  if (world?.config.profile)
    return world.config.profile.indexes
      .map(
        (i) =>
          `[${i.name}]\nhomePath = $SPLUNK_DB/${i.name}/db\ncoldPath = $SPLUNK_DB/${i.name}/colddb\nthawedPath = $SPLUNK_DB/${i.name}/thaweddb\nrepFactor = auto\nfrozenTimePeriodInSecs = ${i.retentionDays * 86400}\nmaxTotalDataSizeMB = 1000000000\n`,
      )
      .join('\n');
  return (
    CLUSTER_INDEXES.map(
      (i) =>
        `[${i}]\nhomePath = $SPLUNK_DB/${i}/db\ncoldPath = $SPLUNK_DB/${i}/colddb\nthawedPath = $SPLUNK_DB/${i}/thaweddb\nrepFactor = auto\nfrozenTimePeriodInSecs = ${i === 'network' ? 7776000 : 31536000}\n`,
    ).join('\n') + '\n'
  );
}
export const clusterIndexes = (world?: World) =>
  world?.config.profile?.indexes.map((i) => i.name) ?? [...CLUSTER_INDEXES];

/** Parsing settings distributed to the indexer cluster (the parsing tier for forwarder data). */
export function clusterPropsConf(): string {
  return [
    '[app:log]',
    'SHOULD_LINEMERGE = false',
    'LINE_BREAKER = ([\\r\\n]+)\\d{4}-\\d{2}-\\d{2}T',
    'TIME_PREFIX = ^',
    'TIME_FORMAT = %Y-%m-%dT%H:%M:%S.%3N%Z',
    'MAX_TIMESTAMP_LOOKAHEAD = 30',
    'TRUNCATE = 20000',
    '',
    '[access_combined]',
    'SHOULD_LINEMERGE = false',
    '',
    '[mysqld]',
    'SHOULD_LINEMERGE = false',
    'TIME_PREFIX = ^',
    '',
  ].join('\n');
}

/** The cluster bundle: files under manager-apps/ on the manager, peer-apps/ on each indexer. */
export function clusterBundle(world?: World): Record<string, string> {
  return {
    '_cluster/local/indexes.conf': clusterIndexesConf(world),
    '_cluster/local/props.conf':
      clusterPropsConf() +
      (world?.config.profile?.dataSources
        .flatMap((d) => d.sourcetypes)
        .map((st) => `\n[${st}]\nSHOULD_LINEMERGE = false\nTZ = UTC\n`)
        .join('') ?? ''),
  };
}

/** Files in etc/system/local for this host. */
export function systemLocal(world: World, p: HostProfile): Record<string, string> {
  const files: Record<string, string> = {};
  const profile = world.config.profile;
  if (profile && p.role === 'search_head') {
    files['authentication.conf'] =
      `[authentication]\nauthType = ${profile.auth.method === 'native' ? 'Splunk' : profile.auth.method === 'saml' ? 'SAML' : 'LDAP'}\n` +
      profile.auth.roleMappings
        .map((m) => `\n[roleMap_${profile.auth.method}]\n${m.group} = ${m.roles.join(';')}\n`)
        .join('');
    files['authorize.conf'] = [...new Set(profile.auth.roleMappings.flatMap((m) => m.roles))]
      .map((r) => `[role_${r}]\n${r==='user'?'':'importRoles = user\n'}`)
      .join('\n');
  }
  const role = p.role;
  const server = [
    `[general]`,
    `serverName = ${p.hostname}`,
    `pass4SymmKey = ${secret(p, 1)}`,
    ``,
    `[sslConfig]`,
    `sslPassword = ${secret(p, 2)}`,
    ``,
  ];
  if (role === 'universal_forwarder') {
    files['server.conf'] = server.join('\n');
    files['inputs.conf'] = `[default]\nhost = ${p.hostname}\n`;
    return files;
  }

  const cm = `https://${infraName(world, 'cluster_manager')}.${DOMAIN}:8089`;
  if (role === 'indexer') {
    server.push(
      '[clustering]',
      'mode = peer',
      `manager_uri = ${cm}`,
      `pass4SymmKey = ${secret(p, 3)}`,
      '',
      '[replication_port://9887]',
      '',
    );
    files['inputs.conf'] = `[default]\nhost = ${p.hostname}\n\n[splunktcp://9997]\ndisabled = 0\n`;
  } else if (role === 'cluster_manager') {
    server.push(
      '[clustering]',
      'mode = manager',
      `replication_factor = ${world.config.profile?.infra.indexerCluster.replicationFactor ?? 3}`,
      `search_factor = ${world.config.profile?.infra.indexerCluster.searchFactor ?? 2}`,
      `pass4SymmKey = ${secret(p, 3)}`,
      'cluster_label = corp_idx_cluster',
      '',
    );
  } else if (role === 'search_head') {
    // Keep most search capacity for people: the scheduler gets a quarter of it.
    files['limits.conf'] = `[scheduler]\nmax_searches_perc = 25\n`;
    server.push(
      '[clustering]',
      'mode = searchhead',
      `manager_uri = ${cm}`,
      `pass4SymmKey = ${secret(p, 3)}`,
      '',
    );
  } else if (role === 'license_manager') {
    server.push('[license]', 'active_group = Enterprise', '');
  } else if (role === 'heavy_forwarder') {
    files['inputs.conf'] = `[default]\nhost = ${p.hostname}\n\n[splunktcp://9997]\ndisabled = 0\n`;
  } else if (role === 'deployment_server') {
    files['serverclass.conf'] = serverclassConf(world);
  }
  if (role !== 'license_manager' && infraByRole(world, 'license_manager').length)
    server.push(
      '[license]',
      `manager_uri = https://${infraName(world, 'license_manager')}.${DOMAIN}:8089`,
      '',
    );
  files['server.conf'] = server.join('\n');
  if (!files['inputs.conf']) files['inputs.conf'] = `[default]\nhost = ${p.hostname}\n`;

  // Everything but indexers forwards its own internal logs to the site's indexers.
  if (role !== 'indexer') {
    const group = outputGroupName(p.site, 'indexers');
    const servers = outputTargets(world, p.site, 'indexers').map((n) => `${n.hostname}.${DOMAIN}:9997`);
    files['outputs.conf'] =
      `[indexAndForward]\nindex = false\n\n[tcpout]\ndefaultGroup = ${group}\nforwardedindex.filter.disable = true\nindexAndForward = false\n\n[tcpout:${group}]\nserver = ${servers.join(', ')}\n`;
  }
  if (profile && (role === 'indexer' || role === 'cluster_manager'))
    files['server.conf'] +=
      '\n[clustering]\nmultisite = ' +
      String(profile.infra.indexerCluster.multisite) +
      '\nsite = ' +
      p.site +
      '\n';
  for (const [name, text] of Object.entries(operationDefaults(world, p)))
    files[name] = (files[name] ?? '') + '\n' + text;
  if (profile && role === 'heavy_forwarder') {
    files['inputs.conf'] =
      (files['inputs.conf'] ?? '') +
      profile.dataSources
        .filter((d) => d.via === p.hostname)
        .flatMap((d) =>
          d.sourcetypes.map(
            (st) =>
              `\n[monitor:///var/log/profile/${d.id}/${st.replace(/:/g, '_')}.log]\ndisabled = 0\nindex = ${d.index}\nsourcetype = ${st}\n`,
          ),
        )
        .join('');
    files['props.conf'] = profile.dataSources
      .filter((d) => d.via === p.hostname)
      .flatMap((d) =>
        d.sourcetypes.map(
          (st) =>
            `[${st}]\nSHOULD_LINEMERGE = false\nTZ = UTC\n${st.startsWith('fgt_') ? 'TIME_PREFIX = ^date=\nTIME_FORMAT = %Y-%m-%d time=%H:%M:%S\n' : ''}`,
        ),
      )
      .join('\n');
  }
  return files;
}

/** Apps that ship with the product (not deployed by the DS). */
export function builtinApps(p: HostProfile, world?: World): string[] {
  if (p.splunk?.product === 'universal_forwarder')
    return [
      'SplunkUniversalForwarder',
      'introspection_generator_addon',
      'journald_input',
      'learned',
      'search',
      'splunk_httpinput',
      'splunk_internal_metrics',
    ];
  const apps = [
    'introspection_generator_addon',
    'journald_input',
    'launcher',
    'learned',
    'search',
    'splunk_httpinput',
    'splunk_instrumentation',
    'splunk_internal_metrics',
  ];
  if (p.role === 'search_head' || p.role === 'cluster_manager')
    apps.push('splunk_monitoring_console', 'splunk_secure_gateway');
  if (world?.config.profile && ['search_head', 'heavy_forwarder', 'deployer'].includes(p.role))
    apps.push(
      ...world.config.profile.apps.filter(
        (a) => a !== 'SplunkEnterpriseSecuritySuite' || p.hostname === 'es01',
      ),
    );
  return [...new Set(apps)].sort();
}

